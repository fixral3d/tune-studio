// Generates src/seed_pages.h: the V3 config pages (by ecuId) from VemsTune's default
// config_<fw>.vemscfg, the same seed the in-browser demo uses (apps/tuner/src/lib/device.ts loadDemoSeed),
// plus VE table/bin offsets for the engine model. Run: node tools/gen_seed.mjs [fw]
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadConfig, parseSiprSection, parseVemsCfg, applyVemsCfg } from '../../../packages/core/dist/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const CFG = join(here, '../../../apps/tuner/public/config');
const fw = process.argv[2] ?? '1.2.34';
const MAIN = `vemsTune-v3-${fw}.ini`;
const defines = new Set(['USE_SUPER_TABLE', 'CELSIUS', 'USE_RAW_LAMBDA_TABLE']);
const read = (p) => {
  try {
    return readFileSync(join(CFG, p), 'latin1');
  } catch {
    try {
      return readFileSync(join(CFG, 'include', p), 'latin1');
    } catch {
      return undefined;
    }
  }
};
const cfg = loadConfig(read(MAIN), MAIN, { defines, resolveInclude: read });
// [SIPR] lives in one of the includes
const files = new Map();
const queue = [MAIN];
while (queue.length) {
  const f = queue.shift();
  if (files.has(f)) continue;
  const t = read(f);
  if (t === undefined) continue;
  files.set(f, t);
  for (const m of t.matchAll(/#\s*include\s+"([^"]+)"/g)) queue.push(m[1]);
}
const sipr = parseSiprSection([...files.values()].filter((t) => /^\s*\[SIPR\]/im.test(t)).join('\n'), defines);
const pages = new Map();
applyVemsCfg(parseVemsCfg(readFileSync(join(CFG, `defaultfirmwareconfigs/config_${fw}.vemscfg`), 'latin1')), { cfg, sipr }, pages);

// prohibit_h/l = firmware code ((maj&7)<<10 | (min&7)<<7 | patch), as an upgraded ECU has it (files/migrate.ts);
// VemsTune shows "Safe Mode Active" when it differs (VemsTuneController::isSafetyModeActive). The shipped default
// config still carries an older code (1.2.32 in config_1.2.34), so set it for the simulated firmware.
{
  const [ma, mi, pa] = fw.split('.').map(Number);
  const code = ((ma & 7) << 10) | ((mi & 7) << 7) | (pa & 0x7f);
  for (const [n, v] of [['prohibit_h', code >> 8], ['prohibit_l', code & 0xff]]) {
    const fld = cfg.byName.get(n);
    if (fld?.kind === 'scalar' && pages.get(fld.page)) pages.get(fld.page)[fld.offset] = v;
  }
}
const byEcu = new Map();
for (const [vt, buf] of pages) {
  const ecu = cfg.vt2ecu.get(vt);
  if (ecu !== undefined) byEcu.set(ecu, buf);
}
const f = (n) => cfg.byName.get(n);
const arr = (n) => {
  const a = f(n);
  if (a?.kind !== 'array') throw new Error(`${n} is not an array`);
  return a;
};
const ve = arr('veTable');
const rb = arr('rpmBinsVE');
const mb = arr('mapBinsVE');
const meta = (a) => `{ ${a.offset}, ${a.type.size}, ${a.shape.dims[0]}, ${a.shape.dims[1] ?? 1}, ${a.scale}, ${a.translate} }`;

let h = `// generated by tools/gen_seed.mjs from defaultfirmwareconfigs/config_${fw}.vemscfg — do not edit\n#pragma once\n#include <stdint.h>\n\n`;
h += `struct SeedPage { uint8_t ecuId; uint16_t len; const uint8_t *data; };\n`;
h += `struct ArrMeta { uint16_t offset; uint8_t size; uint8_t dimX; uint8_t dimY; float scale; float translate; };\n\n`;
const ids = [...byEcu.keys()].sort((a, b) => a - b);
for (const id of ids) {
  const b = byEcu.get(id);
  h += `static const uint8_t seed_page_${id}[${b.length}] = {`;
  h += [...b].map((v, i) => (i % 24 === 0 ? '\n  ' : '') + v).join(',') + '\n};\n';
}
h += `\nstatic const SeedPage SEED_PAGES[] = {\n${ids.map((id) => `  { ${id}, ${byEcu.get(id).length}, seed_page_${id} },`).join('\n')}\n};\n`;
h += `static const int SEED_PAGE_COUNT = ${ids.length};\n`;
// FNV-1a over all seed bytes: a changed seed replaces pages burned with an older one
let fnv = 0x811c9dc5;
for (const id of ids) for (const v of byEcu.get(id)) fnv = Math.imul(fnv ^ v, 0x01000193) >>> 0;
h += `static const uint32_t SEED_HASH = 0x${fnv.toString(16)}u;\n\n`;
h += `// VE model fields (page ecuId ${cfg.vt2ecu.get(ve.page)}); order ${ve.shape.order} (1: idx = y*dimX + x)\n`;
h += `static const uint8_t VE_ECU_ID = ${cfg.vt2ecu.get(ve.page)};\nstatic const uint8_t VE_ORDER = ${ve.shape.order};\n`;
h += `static const ArrMeta VE_TABLE = ${meta(ve)};\nstatic const ArrMeta VE_RPM_BINS = ${meta(rb)};\nstatic const ArrMeta VE_MAP_BINS = ${meta(mb)};\n`;
writeFileSync(join(here, '../src/seed_pages.h'), h);
console.log('pages', ids.map((id) => `${id}:${byEcu.get(id).length}`).join(' '), '| ve', meta(ve), 'rpm', meta(rb), 'map', meta(mb), 'veEcu', cfg.vt2ecu.get(ve.page), 'order', ve.shape.order);
